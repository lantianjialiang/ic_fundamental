// PWR-06 雪崩（UIS）、SOA 与热阻的单测用例，取自 ATE-PWR-module-spec.md §3 PWR-06 的“单测用例”与任务卡数值。
export default async function run({ load, check, near }) {
  const pw = await load('modules/power/core/power.ts')
  const th = await load('modules/power/core/thermal.ts')
  const m = await load('modules/power/pwrUisModel.ts')

  console.log('PWR-06 雪崩能量与雪崩时间')
  check('easJ(1 mH, 10 A, 50 V, 100 V) = 0.1 J', near(pw.easJ(1e-3, 10, 50, 100), 0.1, 1e-9))
  check('t_av = 200 µs（同一组参数）', near(pw.avalancheTime(1e-3, 10, 50, 100), 200e-6, 1e-9))
  const ipk = pw.ipkForEnergy(0.5, 1e-3, 50, 100)
  check('额定 E_AS = 0.5 J 时最大 Ipk ≈ 22.4 A（√500）', near(ipk, 22.36, 0.002), ipk.toFixed(3))

  const t1 = m.simulateUis({ lMh: 1, ipk: 10, vdd: 50, bv: 100, ratedE: 0.2 })
  check('模型：T1 的 E_AS = 0.1 J', near(t1.eas, 0.1, 1e-9), t1.eas.toFixed(4))
  check('模型：T1 的 t_av = 200 µs', near(t1.tav, 200e-6, 1e-9), `${(t1.tav * 1e6).toFixed(1)} µs`)
  const t2 = m.simulateUis({ lMh: 1, ipk: 10, vdd: 50, bv: 100, ratedE: 0.5 })
  check('模型：T2 的最大 Ipk ≈ 22.4 A', near(t2.ipkMax, 22.36, 0.002), t2.ipkMax.toFixed(3))
  const fail = m.simulateUis({ lMh: 1, ipk: 30, vdd: 50, bv: 100, ratedE: 0.5 })
  check('E_AS 超过额定值时判 Fail', fail.pass === false && fail.eas > 0.5, `${fail.eas.toFixed(3)} J`)
  const bad = m.simulateUis({ lMh: 1, ipk: 10, vdd: 120, bv: 100, ratedE: 0.5 })
  check('Vdd ≥ BV 时结果无效（不给出能量）', bad.valid === false && Number.isNaN(bad.eas))
  const clamp = m.simulateUis({ lMh: 1, ipk: 10, vdd: 50, bv: 100, ratedE: 0.5 })
  const vdsInAval = clamp.wave.vds.filter((v, i) => clamp.wave.t[i] < clamp.tav * 0.95)
  check('雪崩期间 Vds 钳位在 BV', vdsInAval.length > 0 && vdsInAval.every((v) => near(v, 100, 1e-9)))

  console.log('PWR-06 热阻 Zth 与温升')
  const z1ms = th.zth({ stages: [{ rth: 0.5, tau: 0.005 }] }, 1e-3)
  check('Zth(1 ms) = 0.5 (1 − e^(−0.2)) ≈ 0.0906', near(z1ms, 0.0906, 0.002), z1ms.toFixed(4))
  const dt = th.pulseHeating(100, 1e-3, { stages: [{ rth: 0.5, tau: 0.005 }] })
  check('P = 100 W、Rth = 0.5 K/W、τ = 5 ms，1 ms 温升 ≈ 9.06 K', near(dt, 9.06, 0.002), dt.toFixed(3))
  const rd = m.thermalReadout(100, 1e-3)
  check('界面读数：thermalReadout 与核心函数一致', near(rd.dT, dt, 1e-9) && near(rd.zth, z1ms, 1e-9))

  console.log('PWR-06 SOA 边界')
  const thermal1ms = m.thermalLimitId(1e-3, 50, 25)
  check('热限制：1 ms、Vds 50 V、Tcase 25 °C 时 Id ≈ 27.6 A', near(thermal1ms, 27.59, 0.002), thermal1ms.toFixed(3))
  check('热限制随脉宽变长而降低', m.thermalLimitId(10e-3, 50, 25) < thermal1ms)
  check('短脉冲区 Zth ∝ √t：10 µs 与 100 µs 的比为 √10', near(m.zthSoa(1e-4) / m.zthSoa(1e-5), Math.sqrt(10), 1e-9))
  const limit = m.soaLimit({ tPulse: 10e-6, vds: 50, tcase: 25 })
  check('10 µs、50 V 时最大电流限为 150 A（热限远高于它）', near(limit, m.SOA_IDMAX, 1e-9), limit.toFixed(1))
  const slow = m.soaLimit({ tPulse: 10e-3, vds: 50, tcase: 25 })
  check('10 ms、50 V 时热限制低于 10 A', slow < 10, `${slow.toFixed(2)} A`)
  check('Vds 超过击穿电压时允许电流为 0', m.soaLimit({ tPulse: 1e-3, vds: 120, tcase: 25 }) === 0)
}
