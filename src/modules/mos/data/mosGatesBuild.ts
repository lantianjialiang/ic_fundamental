export function msgUnused(names: string): LText {
  return loc(
    `输入 ${names} 没有接到任何管子，输出和它无关，所以不可能满足目标。把某个槽位改成它。`,
    `Input ${names} is not connected to any transistor, so the output cannot depend on it and the target cannot be met. Assign a slot to it.`,
  )
}

/** want = 目标在这一行的输出 */
export function msgMismatch(desc: string, want: 0 | 1): LText {
  if (want === 1) {
    return loc(
      `输入 ${desc} 时目标应输出 1，可你的下拉网络在这一行导通，把 OUT 拉到了 GND。下拉网络只应该在目标输出 0 的行导通，检查串联 / 并联和信号分配。`,
      `With inputs ${desc} the target should output 1, but your pull-down conducts in this row and pulls OUT to GND. The pull-down must conduct only on rows where the target outputs 0; check series versus parallel and the signal assignment.`,
    )
  }
  return loc(
    `输入 ${desc} 时目标应输出 0，可你的下拉网络在这一行没有导通，OUT 被上拉网络接到了 VDD。这一行下拉网络必须导通：串联的每只管子输入都要为 1，或者并联的至少一条支路输入全为 1。`,
    `With inputs ${desc} the target should output 0, but your pull-down does not conduct in this row, so the pull-up ties OUT to VDD. The pull-down must conduct here: every series transistor needs input 1, or at least one parallel branch must have all inputs at 1.`,
  )
}
